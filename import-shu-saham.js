const XLSX = require('xlsx');
const fs = require('fs');

const EXCEL_PATH = process.argv[2] || 'SHU Saham 2025.xlsx';

function normalize(str) {
  return String(str || '').trim().toLowerCase().replace(/[^a-z0-9]/g, '');
}

function parseIdr(str) {
  if (!str && str !== 0) return 0;
  const cleaned = String(str).replace(/[^\d.-]/g, '');
  const n = parseFloat(cleaned);
  return isNaN(n) ? 0 : Math.round(n);
}

function findKelompok(sheetName, kelompokList) {
  const sn = normalize(sheetName);
  for (const k of kelompokList) {
    if (normalize(k.nama) === sn) return k;
  }
  for (const k of kelompokList) {
    const kn = normalize(k.nama);
    if (kn.includes(sn) || sn.includes(kn)) return k;
  }
  return null;
}

function escapeSql(str) {
  return String(str || '').replace(/'/g, "''");
}

function main() {
  console.log('=== SHU Saham 2025 → SQL Generator ===');
  console.log('Excel:', EXCEL_PATH);

  if (!fs.existsSync(EXCEL_PATH)) {
    console.error('File tidak ditemukan:', EXCEL_PATH);
    process.exit(1);
  }

  const backup = JSON.parse(fs.readFileSync('backup-supabase.json', 'utf8'));
  const backupKelompok = backup.kelompok || [];

  const wb = XLSX.readFile(EXCEL_PATH);
  console.log('Sheets:', wb.SheetNames.join(', '));

  let sql = [];
  sql.push('-- ============================================');
  sql.push('-- Auto-generated by import-shu-saham.js');
  sql.push('-- Jalankan di Supabase SQL Editor');
  sql.push('-- Backup dulu:');
  sql.push('-- CREATE TABLE kepemilikan_saham_backup AS SELECT * FROM kepemilikan_saham;');
  sql.push('-- ============================================');
  sql.push('');
  sql.push('BEGIN;');

  let totalRows = 0;
  let matchedRows = 0;
  let skippedSheets = 0;

  for (const sheetName of wb.SheetNames) {
    const ws = wb.Sheets[sheetName];
    const rows = XLSX.utils.sheet_to_json(ws, { header: 1, defval: '' });
    if (rows.length < 2) continue;

    const headerRow = rows[1] || [];
    const namaIdx = headerRow.findIndex(h => normalize(String(h)) === 'nama');
    if (namaIdx < 0) {
      console.log(`[${sheetName}] header NAMA tidak ditemukan, skip`);
      continue;
    }

    const matchedKelompok = findKelompok(sheetName, backupKelompok);
    const kelompokId = matchedKelompok ? matchedKelompok.id : null;

    if (!kelompokId) {
      console.log(`[${sheetName}] kelompok "${sheetName}" tidak ditemukan, skip`);
      skippedSheets++;
      continue;
    }

    console.log(`\n[${sheetName}] → ${matchedKelompok.nama} (${kelompokId})`);

    let sheetCount = 0;
    for (let i = 2; i < rows.length; i++) {
      const row = rows[i];
      const nama = String(row[namaIdx] || '').trim();
      if (!nama) continue;
      totalRows++;

      const namaE = escapeSql(nama);
      const namaLower = nama.toLowerCase();

      sql.push(`-- ${nama} | kelompok: ${matchedKelompok.nama}`);
      sql.push(`UPDATE kepemilikan_saham SET kelompok_id = '${kelompokId}' WHERE LOWER(TRIM(nama)) = '${namaLower}' AND (kelompok_id IS NULL OR kelompok_id !== '${kelompokId}');`);
      sql.push(`UPDATE kepemilikan_saham SET anggota_id = (SELECT id FROM users WHERE role = 'nasabah' AND LOWER(TRIM(nama)) = '${namaLower}') WHERE LOWER(TRIM(nama)) = '${namaLower}' AND (anggota_id IS NULL);`);
      matchedRows++;
      sheetCount++;
    }

    if (sheetCount > 0) {
      sql.push(`-- ${sheetName}: ${sheetCount} anggota`);
      sql.push('');
    }
  }

  sql.push('COMMIT;');
  sql.push('');
  sql.push('-- Verifikasi:');
  sql.push('-- SELECT nama, anggota_id, kelompok_id FROM kepemilikan_saham WHERE anggota_id IS NULL LIMIT 20;');
  sql.push('-- SELECT nama, anggota_id, kelompok_id FROM kepemilikan_saham WHERE kelompok_id IS NULL LIMIT 20;');

  const sqlPath = 'kepemilikan_saham_update.sql';
  fs.writeFileSync(sqlPath, sql.join('\n'), 'utf8');

  console.log('\n=== RINGKASAN ===');
  console.log('Total baris anggota:', totalRows);
  console.log('UPDATE statements:', matchedRows * 2);
  console.log('Sheet tidak cocok:', skippedSheets);
  console.log('\nSQL ditulis ke:', sqlPath);
  console.log('\nCara pakai:');
  console.log('1. Buka Supabase Dashboard → SQL Editor');
  console.log('2. Copy paste isi file', sqlPath);
  console.log('3. Jalankan (Run)');
  console.log('4. Cek hasil: SELECT nama, anggota_id, kelompok_id FROM kepemilikan_saham LIMIT 20;');
}

main();